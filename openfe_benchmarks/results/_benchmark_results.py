@dataclass
class Archive:
    """
    Archive metadata for submission.

    Parameters
    ----------
    doi : str
        Digital Object Identifier for the archived submission
    archive_provider : str
        Name of the archive provider (e.g., 'zenodo', 'figshare')
    """

    doi: str
    archive_provider: str


@dataclass
class BenchmarkResults:
    """
    Represents computational results from a submission.yaml file.

    This dataclass mirrors the exact structure of submission.yaml files generated by
    prepare_metadata_submission.py, providing self-validating schema enforcement.

    Use get_benchmark_results() to load from disk.

    Attributes
    ----------
    submission_id : str
        Unique identifier from submission.yaml (required)
    title : str
        Descriptive title (required)
    summary : str
        Short descriptive summary (required)
    tags : list[str]
        List of submission tags (required)
    calculation_type : str
        Type of calculation: 'rbfe', 'asfe', etc. (required)
    authors : list[dict]
        List of author dictionaries with 'name', optional 'affiliation', 'orcid' (required)
    date : str
        Publication/submission date in ISO 8601 format (required)
    results : str
        Results filename (required)
    archive : Archive
        Archive metadata with doi and archive_provider (required)
    license : str
        License identifier (required)
    openfe_version : str, optional
        OpenFE version string
    openmm_version : str, optional
        OpenMM version string
    openff_toolkit_version : str, optional
        OpenFF Toolkit version string
    pontibus_version : str, optional
        Pontibus version string
    mapper : str, optional
        Mapper name and version
    forcefield : list[str] | str, optional
        Protein/solvent force field(s)
    small_molecule_forcefield : str, optional
        Small molecule force field
    partial_charges : str, optional
        Partial charge method
    benchmark_data : dict, optional
        BenchmarkData provenance with network keys
    protocol_settings : list[dict], optional
        Protocol settings for each configuration

    Examples
    --------
    >>> # Load results with computational data
    >>> results = get_benchmark_results('2026-03-18-openmm-840-qa-testing')
    >>>
    >>> # Fast YAML-only load (for CI validation)
    >>> results = get_benchmark_results('2026-03-18-openmm-840-qa-testing', load_results=False)
    >>>
    >>> # Filter submissions globally
    >>> rbfe_submissions = filter_results(tags='rbfe')
    >>> tyk2_submissions = filter_results(system_name='tyk2')
    """

    # Required fields (match submission.yaml structure exactly)
    submission_id: str
    title: str
    summary: str
    tags: list[str]
    calculation_type: str
    authors: list[dict[str, str]]
    date: str
    results: str
    archive: Archive
    license: str
    openfe_version: str
    openmm_version: str
    openff_toolkit_version: str
    partial_charges: str
    benchmark_data: dict[str, Any]
    protocol_settings: list[dict[str, Any]]

    # Optional fields (commonly present in submission.yaml)
    mapper: Optional[str] = None
    forcefield: Optional[list[str] | str] = None
    small_molecule_forcefield: Optional[str] = None
    pontibus_version: Optional[str] = None

    # Computed fields (not from YAML, set by get_benchmark_results)
    raw_results: Optional[dict] = field(default=None, repr=False)
    results_file: Optional[Path] = field(default=None, repr=False)
    submission_file: Optional[Path] = field(default=None, repr=False)

    # FEMap caches (private)
    _dg_femaps_cache: Optional[dict] = field(default=None, repr=False, init=False)
    _ddg_femaps_cache: Optional[dict] = field(default=None, repr=False, init=False)

    def __post_init__(self):
        """
        Validate and normalize fields after dataclass initialization.

        Normalizations performed:
        - Converts single tag string to list
        - Converts single forcefield string to list
        - Converts archive dict to Archive dataclass
        - Initializes FEMap caches to None
        """
        # Ensure tags is a list
        if not isinstance(self.tags, list):
            self.tags = [self.tags]

        # Ensure forcefield is normalized (if present)
        if self.forcefield is not None and not isinstance(self.forcefield, list):
            self.forcefield = [self.forcefield]

        # Convert archive dict to Archive dataclass if needed
        if isinstance(self.archive, dict):
            self.archive = Archive(**self.archive)

        # Initialize FEMap caches
        self._dg_femaps_cache = None
        self._ddg_femaps_cache = None

    def __repr__(self):
        """Return concise string representation with submission_id and calculation_type."""
        return f"BenchmarkResults(submission_id='{self.submission_id}', calculation_type='{self.calculation_type}')"

    def load_raw_results(self) -> None:
        """
        Load computational results JSON file into raw_results.

        Loads the JSON file specified in the results field, with automatic bz2 support.
        Updates the raw_results attribute in place.

        Raises
        ------
        FileNotFoundError
            If results file does not exist
        ValueError
            If results file cannot be loaded

        Examples
        --------
        >>> results = get_benchmark_results('2026-03-18-openmm-840-qa-testing', load_results=False)
        >>> results.raw_results is None
        True
        >>> results.load_raw_results()
        >>> results.raw_results is not None
        True
        """
        # Validate results file exists
        if not self.results_file.exists():
            raise FileNotFoundError(f"Results file not found: {self.results_file}")

        # Load JSON with bz2 support
        open_func = bz2.open if ".bz2" in str(self.results_file) else open
        try:
            with open_func(self.results_file, "rt") as handle:
                self.raw_results = json.load(handle, cls=JSON_HANDLER.decoder)
        except Exception as e:
            raise ValueError(f"Error loading results file {self.results_file}: {e}")

        logger.debug(f"Loaded raw_results for {self.submission_id}")

    @property
    def dg_femaps(self) -> dict[tuple[str, str], FEMap]:
        """
        Lazy-loaded FEMaps for absolute (dg) results grouped by system.

        Returns FEMaps with calculated and experimental data for both ASFE and RBFE submissions:
        - ASFE: absolute solvation free energies with experimental comparison
        - RBFE: absolute binding free energies (reference values)

        Results are cached after first access to avoid repeated processing.

        Returns
        -------
        dict[tuple[str, str], FEMap]
            Dictionary mapping (system_group, system_name) to FEMap objects

        Raises
        ------
        ValueError
            If raw_results is None (load_results=False was used) or if 'dg' key not found

        Examples
        --------
        >>> # ASFE submission
        >>> results = BenchmarkResults(submission_id='2026-08-06-openff-2.3.0-solvation_set_freesolv')
        >>> femaps = results.dg_femaps
        >>> for (group, name), femap in femaps.items():
        ...     print(f"{group}/{name}: {len(femap.edges)} calculations")
        >>>
        >>> # RBFE submission
        >>> results = BenchmarkResults(submission_id='2026-02-12_sage_230_jacs')
        >>> femaps = results.dg_femaps
        >>> for (group, name), femap in femaps.items():
        ...     print(f"{group}/{name}: absolute binding values")
        """
        if self.raw_results is None:
            raise ValueError(
                "Cannot access dg_femaps: raw_results is None. "
                "Initialize with load_results=True to access computational data."
            )

        # Return cached value if available
        if self._dg_femaps_cache is not None:
            return self._dg_femaps_cache

        # Build FEMaps from absolute results (both ASFE and RBFE supported)
        if "dg" not in self.raw_results:
            raise ValueError(
                f"'dg' key not found in raw_results for {self.calculation_type} submission {self.submission_id}. "
                f"Available keys: {list(self.raw_results.keys())}"
            )

        # Build FEMaps and cache, passing calculation type
        logger.info("Computing FEMaps for dg results - first access may be slow")
        self._dg_femaps_cache = build_femap_from_absolute_results(
            self.raw_results["dg"], calculation_type=self.calculation_type
        )

        return self._dg_femaps_cache

    @property
    def ddg_femaps(self) -> dict[tuple[str, str], FEMap]:
        """
        Lazy-loaded FEMaps for relative (ddg) results grouped by system.

        Returns FEMaps with calculated and experimental binding free energy data.
        Results are cached after first access to avoid repeated processing.

        Returns
        -------
        dict[tuple[str, str], FEMap]
            Dictionary mapping (system_group, system_name) to FEMap objects

        Raises
        ------
        ValueError
            If raw_results is None (load_results=False was used) or if 'ddg' key not found

        Examples
        --------
        >>> results = BenchmarkResults(submission_id='2026-03-18-openmm-840-qa-testing')
        >>> femaps = results.ddg_femaps
        >>> for (group, name), femap in femaps.items():
        ...     print(f"{group}/{name}: {len(femap.edges)} edges")
        """
        if self.raw_results is None:
            raise ValueError(
                "Cannot access ddg_femaps: raw_results is None. "
                "Initialize with load_results=True to access computational data."
            )

        if "ddg" not in self.raw_results:
            raise ValueError(
                f"'ddg' key not found in raw_results for {self.submission_id}. "
                f"Available keys: {list(self.raw_results.keys())}"
            )

        # Return cached value if available
        if self._ddg_femaps_cache is not None:
            return self._ddg_femaps_cache

        # Build FEMaps and cache
        logger.info("Computing FEMaps for ddg results - first access may be slow")
        self._ddg_femaps_cache = build_femap_from_relative_results(
            self.raw_results["ddg"]
        )

        return self._ddg_femaps_cache


# Factory function helpers


def _load_and_validate_yaml(submission_file: Path, submission_id: str) -> dict:
    """
    Load and validate YAML structure from submission file.

    Parameters
    ----------
    submission_file : Path
        Path to submission.yaml file
    submission_id : str
        Expected submission identifier

    Returns
    -------
    dict
        Loaded YAML data

    Raises
    ------
    ValueError
        If YAML cannot be parsed or submission_id doesn't match
    """
    try:
        with open(submission_file, "r") as f:
            yaml_data = yaml.safe_load(f)
    except Exception as e:
        raise ValueError(f"Error reading submission.yaml for {submission_id}: {e}")

    # Validate submission_id matches directory name
    yaml_submission_id = yaml_data.get("submission_id")
    if yaml_submission_id != submission_id:
        raise ValueError(
            f"submission_id mismatch: YAML has '{yaml_submission_id}', expected '{submission_id}'"
        )

    return yaml_data


def _extract_benchmark_fields(yaml_data: dict, submission_id: str) -> BenchmarkResults:
    """
    Extract and validate fields from YAML data to construct BenchmarkResults.

    Uses pop() to consume fields and detect unknown entries.

    Parameters
    ----------
    yaml_data : dict
        Loaded YAML data
    submission_id : str
        Submission identifier for error messages

    Returns
    -------
    BenchmarkResults
        Constructed dataclass instance (without file paths or loaded results)

    Raises
    ------
    ValueError
        If required fields are missing or unknown fields are present
    """
    yaml_fields = yaml_data.copy()

    try:
        benchmark_results = BenchmarkResults(
            # Required fields
            submission_id=yaml_fields.pop("submission_id"),
            title=yaml_fields.pop("title"),
            summary=yaml_fields.pop("summary"),
            tags=yaml_fields.pop("tags"),
            calculation_type=yaml_fields.pop("calculation_type"),
            authors=yaml_fields.pop("authors"),
            date=yaml_fields.pop("date"),
            results=yaml_fields.pop("results"),
            archive=yaml_fields.pop("archive"),
            license=yaml_fields.pop("license"),
            openfe_version=yaml_fields.pop("openfe_version"),
            openmm_version=yaml_fields.pop("openmm_version"),
            openff_toolkit_version=yaml_fields.pop("openff_toolkit_version"),
            partial_charges=yaml_fields.pop("partial_charges"),
            benchmark_data=yaml_fields.pop("benchmark_data"),
            protocol_settings=yaml_fields.pop("protocol_settings"),
            # Optional fields
            mapper=yaml_fields.pop("mapper", None),
            forcefield=yaml_fields.pop("forcefield", None),
            small_molecule_forcefield=yaml_fields.pop(
                "small_molecule_forcefield", None
            ),
            pontibus_version=yaml_fields.pop("pontibus_version", None),
        )
    except KeyError as e:
        raise ValueError(
            f"Invalid submission.yaml for {submission_id}: missing required field {e}"
        )

    # Check for unknown fields remaining in yaml_fields
    if yaml_fields:
        unknown_fields = list(yaml_fields.keys())
        raise ValueError(
            f"Unknown fields in submission.yaml for {submission_id}: {unknown_fields}"
        )

    return benchmark_results


def get_benchmark_results(
    submission_id: str,
    load_results: bool = True,
) -> BenchmarkResults:
    """
    Factory function to load BenchmarkResults from a submission_id.

    This is the primary way to load BenchmarkResults objects from disk.
    Loads submission.yaml and optionally the computational results JSON.

    Parameters
    ----------
    submission_id : str
        Unique submission identifier (e.g., '2026-03-18-openmm-840-qa-testing')
    load_results : bool, default=True
        If True, load computational_results.json. If False, only load YAML metadata
        (for fast CI validation). When False, raw_results will be None.

    Returns
    -------
    BenchmarkResults
        Loaded results object

    Raises
    ------
    FileNotFoundError
        If submission_id directory or submission.yaml not found
    ValueError
        If submission.yaml is invalid or has mismatched submission_id

    Examples
    --------
    >>> results = get_benchmark_results('2026-03-18-openmm-840-qa-testing')
    >>> results.title
    'OpenFE RBFE - Multi-set Benchmark...'

    >>> # Fast YAML-only load for validation
    >>> results = get_benchmark_results('2026-03-18-openmm-840-qa-testing', load_results=False)
    >>> print(results.calculation_type)
    'rbfe'
    """
    # Construct and validate paths
    submission_dir = _RESULTS_DIR / submission_id
    submission_file = submission_dir / "submission.yaml"

    if not submission_dir.exists():
        raise FileNotFoundError(f"Submission not found: {submission_id}")

    if not submission_file.exists():
        raise FileNotFoundError(f"submission.yaml not found for: {submission_id}")

    # Load and validate YAML
    yaml_data = _load_and_validate_yaml(submission_file, submission_id)

    # Extract fields to construct BenchmarkResults
    benchmark_results = _extract_benchmark_fields(yaml_data, submission_id)

    # Set computed fields
    results_filename = yaml_data["results"]
    benchmark_results.results_file = submission_dir / results_filename
    benchmark_results.submission_file = submission_file

    # Conditionally load computational results
    if load_results:
        benchmark_results.load_raw_results()

    logger.debug(
        f"Loaded BenchmarkResults: {benchmark_results.submission_id} (load_results={load_results})"
    )

    return benchmark_results


# Standalone filtering functions


def filter_results(
    tags_mode: str = "all", load_results: Optional[bool] = None, **filters
) -> list[BenchmarkResults]:
    """
    Filter submissions by metadata and/or raw result-entry fields.

    This function scans all submission directories under ``openfe_benchmarks/results``
    and returns matching ``BenchmarkResults`` objects.

    Filters targeting ``BenchmarkResults`` fields (e.g. ``tags``, ``date``) are applied
    at submission level. Filters targeting raw result entries (e.g. ``system_name``,
    ``dg``) are applied to ``dg`` and ``ddg`` entries; a submission matches when any
    single result entry satisfies all result-entry filters.

    Parameters
    ----------
    tags_mode : {'all', 'any'}, default='all'
        When filtering by multiple tags:
        - 'all': submission must have ALL specified tags (AND logic, default)
        - 'any': submission must have ANY specified tag (OR logic)
    load_results : bool, optional
        Whether to load raw computational results while filtering.
        If None (default), automatically enabled when result-entry filters are used.
    **filters : dict
        Field=value pairs to filter by. Values can be:
        - Single value: exact match (or wildcard if contains * or ?)
        - List: matches if ANY value matches (OR logic), except ``tags`` honoring
          ``tags_mode``
        - Use ``exclude_`` prefix for NOT logic (e.g. ``exclude_tags=['test']``)

    Returns
    -------
    list[BenchmarkResults]
        Matching BenchmarkResults objects
    """
    if tags_mode not in {"all", "any"}:
        raise ValueError(f"Invalid tags_mode: {tags_mode}. Must be 'all' or 'any'")

    if not _RESULTS_DIR.exists():
        raise FileNotFoundError(f"Results directory not found: {_RESULTS_DIR}")

    submission_filters = {
        key: value for key, value in filters.items() if _is_submission_filter_key(key)
    }
    result_entry_filters = {
        key: value
        for key, value in filters.items()
        if not _is_submission_filter_key(key)
    }

    if load_results is None:
        load_results = bool(result_entry_filters)

    matched_submissions: list[BenchmarkResults] = []
    for submission_dir in sorted(_RESULTS_DIR.iterdir()):
        if not submission_dir.is_dir():
            continue

        submission_file = submission_dir / "submission.yaml"
        if not submission_file.exists():
            continue

        try:
            benchmark_results = get_benchmark_results(
                submission_id=submission_dir.name,
                load_results=load_results,
            )
        except (FileNotFoundError, ValueError) as exc:
            logger.warning(
                "Skipping submission '%s' during filtering: %s",
                submission_dir.name,
                exc,
            )
            continue

        if not all(
            _match_submission_filter(benchmark_results, key, value, tags_mode)
            for key, value in submission_filters.items()
        ):
            continue

        if not result_entry_filters:
            matched_submissions.append(benchmark_results)
            continue

        if benchmark_results.raw_results is None:
            continue

        all_results = []
        if "dg" in benchmark_results.raw_results:
            all_results.extend(benchmark_results.raw_results["dg"])
        if "ddg" in benchmark_results.raw_results:
            all_results.extend(benchmark_results.raw_results["ddg"])

        if any(
            all(
                _match_filter(result, benchmark_results, key, value, tags_mode)
                for key, value in result_entry_filters.items()
            )
            for result in all_results
        ):
            matched_submissions.append(benchmark_results)

    return matched_submissions


def _is_submission_filter_key(filter_key: str) -> bool:
    """Return True if filter key targets a BenchmarkResults-level field."""
    if filter_key.startswith("exclude_"):
        filter_key = filter_key[len("exclude_") :]

    root_key = filter_key.split("__", 1)[0]
    return root_key in BenchmarkResults.__dataclass_fields__


def _match_submission_filter(
    benchmark_results: BenchmarkResults,
    filter_key: str,
    filter_val: Union[str, list, Any],
    tags_mode: str,
) -> bool:
    """Check if a submission-level field matches a filter predicate."""
    EXCLUDE_PREFIX = "exclude_"
    negate = False
    if filter_key.startswith(EXCLUDE_PREFIX):
        negate = True
        filter_key = filter_key[len(EXCLUDE_PREFIX) :]

    comparison_op = None
    if isinstance(filter_val, str):
        comparison_op, filter_val = _parse_inline_operator(filter_val)

    if "__" in filter_key:
        value = _get_nested_value(benchmark_results, filter_key)
    else:
        value = getattr(benchmark_results, filter_key, None)

    if value is None:
        result_matched = False
        return not result_matched if negate else result_matched

    if comparison_op is not None:
        result_matched = _compare_values(value, filter_val, comparison_op, filter_key)
    else:
        result_matched = _match_value(value, filter_val, filter_key, tags_mode)

    return not result_matched if negate else result_matched


def _get_nested_value(result: Any, nested_key: str) -> Optional[Any]:
    """
    Extract value from nested dictionary using double-underscore separated keys.

    Parameters
    ----------
    result : Any
        Result object or dictionary to extract from
    nested_key : str
        Nested key with __ separator (e.g., 'protocol_settings__temperature')

    Returns
    -------
    Optional[Any]
        The nested value if found, None otherwise

    Examples
    --------
    >>> result = {'protocol_settings': {'temperature': '298.15 K'}}
    >>> _get_nested_value(result, 'protocol_settings__temperature')
    '298.15 K'
    >>> _get_nested_value(result, 'protocol_settings__missing')
    None
    """
    keys = nested_key.split("__")
    value = result
    for key in keys:
        if isinstance(value, dict):
            value = value.get(key, None)
        elif isinstance(value, list):
            # Support list-of-dicts nesting (e.g. protocol_settings is a list of dicts)
            next_values = []
            for item in value:
                if isinstance(item, dict):
                    nested = item.get(key, None)
                else:
                    nested = getattr(item, key, None)

                if nested is not None:
                    next_values.append(nested)

            value = next_values
            if not value:
                return None
        else:
            value = getattr(value, key, None)
            if value is None:
                return None
    return value


def _match_filter(
    result: dict,
    benchmark_results: BenchmarkResults,
    filter_key: str,
    filter_val: Union[str, list, Any],
    tags_mode: str = "all",
) -> bool:
    """
    Check if a result matches a filter predicate.

    Parameters
    ----------
    result : dict
        Result dictionary to check
    benchmark_results : BenchmarkResults
        BenchmarkResults object (for fallback field access to top-level metadata)
    filter_key : str
        Filter key (may have exclude_ prefix, may have __ for nested fields)
    filter_val : Union[str, list, Any]
        Filter value (single value for exact match, list for OR logic,
        or string with leading comparison operator like '>=1.0.0')
    tags_mode : str, default='all'
        Mode for tags filtering: 'all' (AND) or 'any' (OR)

    Returns
    -------
    bool
        True if result matches filter, False otherwise
    """
    # Handle NOT logic (exclude_ prefix)
    EXCLUDE_PREFIX = "exclude_"
    negate = False
    if filter_key.startswith(EXCLUDE_PREFIX):
        negate = True
        filter_key = filter_key[len(EXCLUDE_PREFIX) :]  # Remove 'exclude_' prefix

    # Parse inline comparison operators from filter value (e.g., '>=2026-01-01')
    comparison_op = None
    if isinstance(filter_val, str):
        comparison_op, filter_val = _parse_inline_operator(filter_val)

    # Extract field value (handle nested access)
    if "__" in filter_key:
        value = _get_nested_value(result, filter_key)
        if value is None:
            # Field not found in result
            result_matched = False
            return not result_matched if negate else result_matched
    else:
        # Direct field access
        # First try result dict, then fall back to BenchmarkResults attributes for top-level fields
        if filter_key in result:
            value = result[filter_key]
        elif hasattr(benchmark_results, filter_key):
            value = getattr(benchmark_results, filter_key)
        else:
            # Field not found
            result_matched = False
            return not result_matched if negate else result_matched

    # Apply comparison or match logic
    if comparison_op is not None:
        result_matched = _compare_values(value, filter_val, comparison_op, filter_key)
    else:
        result_matched = _match_value(value, filter_val, filter_key, tags_mode)

    # Apply negation if needed
    return not result_matched if negate else result_matched


def _match_value(
    result_value: Any,
    filter_val: Union[str, list, Any],
    filter_key: str,
    tags_mode: str,
) -> bool:
    """
    Check if a result value matches a filter value with special tags handling.

    Parameters
    ----------
    result_value : Any
        Value from result to check against the filter
    filter_val : Union[str, list, Any]
        Filter value - single value for exact match, list for OR logic
    filter_key : str
        Filter key name (used for special handling of 'tags' field)
    tags_mode : str
        Mode for tags filtering: 'all' (AND logic) or 'any' (OR logic)

    Returns
    -------
    bool
        True if value matches filter, False otherwise

    Raises
    ------
    ValueError
        If tags_mode is not 'all' or 'any'
    """
    # Special handling for tags field with list filter_val
    if filter_key == "tags" and isinstance(filter_val, list):
        # Ensure result_value is a list
        result_tags = result_value if isinstance(result_value, list) else [result_value]

        if tags_mode == "all":
            # AND logic: result must have ALL filter tags
            return all(tag in result_tags for tag in filter_val)
        elif tags_mode == "any":
            # OR logic: result must have ANY filter tag
            return any(tag in result_tags for tag in filter_val)
        else:
            raise ValueError(f"Invalid tags_mode: {tags_mode}. Must be 'all' or 'any'")

    # OR logic for list filter values (non-tags fields)
    if isinstance(filter_val, list):
        # Check if ANY filter value matches
        return any(_match_single_value(result_value, fv) for fv in filter_val)
    else:
        # Single value match
        return _match_single_value(result_value, filter_val)


def _match_single_value(result_value: Any, filter_val: Any) -> bool:
    """
    Check if a single result value matches a single filter value.

    Handles wildcards and list-valued result fields.

    Parameters
    ----------
    result_value : Any
        Value from result to check
    filter_val : Any
        Single filter value (not a list)

    Returns
    -------
    bool
        True if value matches, False otherwise
    """
    # Handle list-valued result fields (check if ANY element matches)
    if isinstance(result_value, list):
        return any(_match_single_value(item, filter_val) for item in result_value)

    # Wildcard matching for strings
    if isinstance(filter_val, str) and ("*" in filter_val or "?" in filter_val):
        return fnmatch.fnmatch(str(result_value), filter_val)

    # Exact match
    return result_value == filter_val


def _parse_inline_operator(value: str) -> tuple[Optional[str], str]:
    """
    Parse inline comparison operator from a filter value string.

    Detects operators like >=, >, <=, < at the start of the value.

    Parameters
    ----------
    value : str
        Filter value that may contain an inline operator (e.g., ">=2026-01-01")

    Returns
    -------
    tuple[Optional[str], str]
        (operator, value) where operator is '>=', '>', '<=', '<', or None
        and value is the remaining string after removing the operator

    Examples
    --------
    >>> _parse_inline_operator(">=2026-01-01")
    ('>=', '2026-01-01')
    >>> _parse_inline_operator("<1.0.0")
    ('<', '1.0.0')
    >>> _parse_inline_operator("2026-01-01")
    (None, '2026-01-01')
    """
    # Match >=, >, <=, < at the start of the string
    match = re.match(r"^(>=|>|<=|<)(.+)$", value)
    if not match:
        return None, value

    op_str, remaining = match.groups()
    return op_str, remaining.strip()


def _compare_values(
    result_value: Any, filter_val: Any, operator: str, field_name: str = ""
) -> bool:
    """
    Compare result value against filter value using a comparison operator.

    Handles semantic version comparison, date comparison, pint Quantity comparison,
    and string comparison. Issues a warning if comparison operators are used with
    non-date/version fields.

    Parameters
    ----------
    result_value : Any
        Value from result to compare
    filter_val : Any
        Filter value to compare against
    operator : str
        Comparison operator: '<', '<=', '>', or '>='
    field_name : str, optional
        Name of the field being compared (for warning messages)

    Returns
    -------
    bool
        True if comparison succeeds, False otherwise

    Raises
    ------
    ValueError
        If a Quantity comparison is requested with an invalid quantity string,
        unsupported filter type, or incompatible dimensions.

    Examples
    --------
    >>> _compare_values('2026-01-15', '2026-01-01', '>=', 'date')
    True
    >>> _compare_values('1.0.0', '2.0.0', '<', 'openfe_version')
    True
    >>> _compare_values('8.2.0', '8.1.0', '>', 'openmm_version')
    True
    >>> # pint Quantity comparison (from raw_results JSON)
    >>> import pint
    >>> ureg = pint.UnitRegistry()
    >>> q1 = ureg.Quantity(298.15, 'kelvin')
    >>> _compare_values(q1, '300 K', '<')
    True
    >>> _compare_values(q1, '25 celsius', '>=')  # Unit conversion handled automatically
    True
    """
    # For list-valued nested fields, match if any element satisfies the comparison.
    if isinstance(result_value, list):
        return any(
            _compare_values(item, filter_val, operator, field_name)
            for item in result_value
        )

    _warn_if_nonsemantic_comparison(result_value, operator, field_name)

    # Handle datetime.date objects (from YAML parsing)
    if isinstance(result_value, date_type):
        result_value, filter_val = _coerce_date_values(result_value, filter_val)
        return _apply_comparison_operator(result_value, filter_val, operator)

    # Handle pint Quantity objects (from JSON_HANDLER deserialization)
    if isinstance(result_value, pint.Quantity):
        filter_val = _coerce_quantity_filter_value(result_value, filter_val, field_name)

        # Compare Quantities (pint handles unit conversion automatically)
        try:
            return _apply_comparison_operator(result_value, filter_val, operator)
        except pint.errors.DimensionalityError as e:
            raise ValueError(
                f"Incompatible units for Quantity comparison on field '{field_name}': {e}"
            ) from e

    # Try semantic version comparison (for version fields)
    try:
        result_ver = Version(str(result_value))
        filter_ver = Version(str(filter_val))
        return _apply_comparison_operator(result_ver, filter_ver, operator)

    except (InvalidVersion, TypeError):
        # Fall back to string comparison
        result_str = str(result_value)
        filter_str = str(filter_val)
        return _apply_comparison_operator(result_str, filter_str, operator)


def _warn_if_nonsemantic_comparison(
    result_value: Any, operator: str, field_name: str
) -> None:
    """Warn when comparison operators are used on fields that may not compare semantically."""
    comparison_allowed_fields = {
        "date",
        "openfe_version",
        "openmm_version",
        "openff_toolkit_version",
        "pontibus_version",
    }
    if (
        field_name
        and field_name not in comparison_allowed_fields
        and not field_name.endswith("_version")
        and not isinstance(result_value, pint.Quantity)
    ):
        warnings.warn(
            f"Comparison operator '{operator}' used with field '{field_name}'. "
            "Comparison operators are designed for date and version fields. "
            "Results may not be semantically meaningful for other field types.",
            UserWarning,
            stacklevel=4,
        )


def _coerce_date_values(
    result_value: date_type, filter_val: Any
) -> tuple[date_type | str, Any]:
    """Coerce date comparisons, preserving fallback-to-string behavior on parse failure."""
    coerced_result_value: date_type | str = result_value
    if isinstance(filter_val, str):
        try:
            # Parse ISO format date string YYYY-MM-DD
            filter_val = date_type.fromisoformat(filter_val)
        except (ValueError, AttributeError):
            # If parsing fails, compare strings to preserve previous behavior
            coerced_result_value = result_value.isoformat()

    return coerced_result_value, filter_val


def _coerce_quantity_filter_value(
    result_value: pint.Quantity, filter_val: Any, field_name: str
) -> Any:
    """Convert quantity filter inputs into pint.Quantity using the result value registry."""
    if isinstance(filter_val, str):
        try:
            ureg = result_value._REGISTRY
            return ureg.Quantity(filter_val)
        except (ValueError, pint.errors.UndefinedUnitError, AttributeError) as exc:
            raise ValueError(
                f"Invalid quantity filter value '{filter_val}' for field '{field_name}'. "
                "Provide a valid quantity string with units."
            ) from exc

    if isinstance(filter_val, pint.Quantity):
        return filter_val

    raise ValueError(
        f"Invalid filter type '{type(filter_val).__name__}' for Quantity field '{field_name}'. "
        "Provide a quantity string or pint.Quantity value."
    )


def _apply_comparison_operator(left: Any, right: Any, operator: str) -> bool:
    """Apply one of <, <=, >, >= operators to two comparable values."""
    operator_map = {
        "<": py_operator.lt,
        "<=": py_operator.le,
        ">": py_operator.gt,
        ">=": py_operator.ge,
    }
    compare_func = operator_map.get(operator)
    if compare_func is None:
        raise ValueError(f"Unknown comparison operator: {operator}")

    return compare_func(left, right)
